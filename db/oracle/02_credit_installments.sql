-- EASYCREDIT.CREDIT_INSTALLMENTS (jadwal angsuran, dibuat saat pengajuan di-approve)
-- Idempotent: aman dijalankan berulang.
-- Butuh 01_credit_applications.sql sudah dijalankan.

SET SERVEROUTPUT ON

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE EASYCREDIT.CREDIT_INSTALLMENTS (
            ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
            APPLICATION_ID NUMBER        NOT NULL,
            INSTALLMENT_NO NUMBER        NOT NULL,
            DUE_DATE       DATE          NOT NULL,
            AMOUNT         NUMBER(15,2)  NOT NULL,
            STATUS         VARCHAR2(10)  DEFAULT 'PENDING' NOT NULL,
            CONSTRAINT PK_CREDIT_INSTALLMENTS PRIMARY KEY (ID),
            CONSTRAINT CK_CREDIT_INST_STATUS CHECK (STATUS IN ('PENDING', 'PAID')),
            CONSTRAINT UQ_CREDIT_INST_APP_NO UNIQUE (APPLICATION_ID, INSTALLMENT_NO)
        )]';
    DBMS_OUTPUT.PUT_LINE('CREDIT_INSTALLMENTS dibuat.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('CREDIT_INSTALLMENTS sudah ada, dilewati.');
        ELSE
            RAISE;
        END IF;
END;
/

-- Hanya pengajuan DRAFT yang boleh dihapus (belum punya angsuran);
-- CASCADE menjaga konsistensi kalau data dihapus manual.
BEGIN
    EXECUTE IMMEDIATE q'[
        ALTER TABLE EASYCREDIT.CREDIT_INSTALLMENTS
            ADD CONSTRAINT FK_CREDIT_INST_APPLICATION
            FOREIGN KEY (APPLICATION_ID) REFERENCES EASYCREDIT.CREDIT_APPLICATIONS (ID)
            ON DELETE CASCADE]';
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE NOT IN (-2275, -2264) THEN RAISE; END IF;
END;
/
