-- EASYCREDIT.CREDIT_APPLICATIONS
-- Idempotent: aman dijalankan berulang (ORA-00955 / ORA-02275 / ORA-02264 diabaikan).
-- Butuh tabel EASYCREDIT.CUSTOMERS sudah ada.
-- Kolom CUSTOMER_ID, STATUS, APPROVED_BY, APPROVED_AT dipakai stored procedure Day 6.

SET SERVEROUTPUT ON

BEGIN
    EXECUTE IMMEDIATE q'[
        CREATE TABLE EASYCREDIT.CREDIT_APPLICATIONS (
            ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
            CUSTOMER_ID   NUMBER        NOT NULL,
            AMOUNT        NUMBER(15,2)  NOT NULL,
            TENOR_MONTHS  NUMBER        NOT NULL,
            INTEREST_RATE NUMBER(5,2)   NOT NULL,
            PURPOSE       VARCHAR2(200),
            STATUS        VARCHAR2(20)  DEFAULT 'DRAFT' NOT NULL,
            CREDIT_SCORE  NUMBER,
            APPROVED_BY   VARCHAR2(100),
            APPROVED_AT   DATE,
            CREATED_AT    DATE          DEFAULT SYSDATE NOT NULL,
            UPDATED_AT    DATE          DEFAULT SYSDATE NOT NULL,
            CONSTRAINT PK_CREDIT_APPLICATIONS PRIMARY KEY (ID),
            CONSTRAINT CK_CREDIT_APP_STATUS
                CHECK (STATUS IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED')),
            CONSTRAINT CK_CREDIT_APP_AMOUNT CHECK (AMOUNT > 0),
            CONSTRAINT CK_CREDIT_APP_TENOR  CHECK (TENOR_MONTHS BETWEEN 1 AND 120)
        )]';
    DBMS_OUTPUT.PUT_LINE('CREDIT_APPLICATIONS dibuat.');
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE = -955 THEN
            DBMS_OUTPUT.PUT_LINE('CREDIT_APPLICATIONS sudah ada, dilewati.');
        ELSE
            RAISE;
        END IF;
END;
/

-- FK terpisah supaya tetap ditambahkan kalau tabel dibuat tanpa FK sebelumnya.
BEGIN
    EXECUTE IMMEDIATE q'[
        ALTER TABLE EASYCREDIT.CREDIT_APPLICATIONS
            ADD CONSTRAINT FK_CREDIT_APP_CUSTOMER
            FOREIGN KEY (CUSTOMER_ID) REFERENCES EASYCREDIT.CUSTOMERS (ID)]';
EXCEPTION
    WHEN OTHERS THEN
        -- -2275: FK sudah ada, -2264: nama constraint sudah dipakai
        IF SQLCODE NOT IN (-2275, -2264) THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX EASYCREDIT.IX_CREDIT_APP_CUSTOMER ON EASYCREDIT.CREDIT_APPLICATIONS (CUSTOMER_ID)';
EXCEPTION
    -- -955: nama sudah dipakai, -1408: kolom sudah di-index
    WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX EASYCREDIT.IX_CREDIT_APP_STATUS ON EASYCREDIT.CREDIT_APPLICATIONS (STATUS)';
EXCEPTION
    WHEN OTHERS THEN IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/
